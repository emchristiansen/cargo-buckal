    #[test]
    fn test_tables_render_sorted_and_marked() {
        let tables = PackageTables {
            whole_repository: [
                "third-party/rust/git/gdep/0.1.0",
                "third-party/rust/crates/zeta/1.0.0",
                "third-party/rust/crates/alpha/0.2.0",
            ]
            .into_iter()
            .map(|dir| (dir.to_owned(), format!("root//{dir}:")))
            .collect(),
            source_tree: ["app", ".", "a\"b", "-x"].map(str::to_owned).into(),
        };
        let text = tables.render();
        assert!(is_generated_tables(&text), "{text}");
        assert!(
            text.contains(
                "GENERATED_WHOLE_REPOSITORY_PACKAGES = {\n    \"third-party/rust/crates/alpha/0.2.0\": \"root//third-party/rust/crates/alpha/0.2.0:\",\n    \"third-party/rust/crates/zeta/1.0.0\": \"root//third-party/rust/crates/zeta/1.0.0:\",\n    \"third-party/rust/git/gdep/0.1.0\": \"root//third-party/rust/git/gdep/0.1.0:\",\n}\n"
            ),
            "{text}"
        );
        assert!(
            text.ends_with(
                "GENERATED_SOURCE_TREE_PACKAGES = [\n    \"-x\",\n    \".\",\n    \"a\\\"b\",\n    \"app\",\n]\n"
            ),
            "{text}"
        );
        // The text is valid Starlark.
        starlark_syntax::syntax::AstModule::parse(
            "tables.bzl",
            text.clone(),
            &starlark_syntax::syntax::Dialect::Extended,
        )
        .unwrap();

        let empty = PackageTables::default().render();
        assert!(empty.contains("GENERATED_WHOLE_REPOSITORY_PACKAGES = {}\n"));
        assert!(empty.ends_with("GENERATED_SOURCE_TREE_PACKAGES = []\n"));
        assert!(!is_generated_tables(
            "# @generated by `cargo buckal`\nX = 1\n"
        ));
        assert!(!is_generated_tables("X = 1\n"));
    }

    /// A standalone universe's record, as its own generation writes it.
    fn standalone_record(ids: &[&str]) -> String {
        let mut record = "version = 17\n\n[fingerprints]\n".to_owned();
        for id in ids {
            record.push_str(&format!("\"{id}\" = \"{}\"\n", "00".repeat(32)));
        }
        record
    }

    #[test]
    fn test_standalone_universes_are_classified_by_their_own_records() {
        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        for path in [
            "BUCK",
            "Cargo.toml",
            "buckal.toml",
            "guests/ws/Cargo.toml",
            "guests/ws/buckal.toml",
            "guests/ws/BUCK",
            // A workspace without its own configuration is not a universe.
            "plain/Cargo.toml",
            "plain/BUCK",
            // Never generated: neither record nor vendor tree.
            "fresh/Cargo.toml",
            "fresh/buckal.toml",
            "third-party/rust/standalone/ws/crates/sdep/2.0.0/BUCK",
            "third-party/rust/standalone/ws/git/gdep/0.1.0/BUCK",
            // In the universe's vendor tree but not in its record: not generated.
            "third-party/rust/standalone/ws/crates/stray/0.1.0/BUCK",
        ] {
            touch(root, path);
        }
        std::fs::write(
            root.join("guests/ws/buckal.snap"),
            standalone_record(&[
                "path+file://($WORKSPACE)#ws@0.1.0",
                "registry+https://github.com/rust-lang/crates.io-index#sdep@2.0.0",
                "git+https://example.com/g.git?rev=abc#gdep@0.1.0",
            ]),
        )
        .unwrap();
        let layout = CellLayout::parse("[cells]\nroot = .\n").unwrap();
        let standalone = standalone_package_dirs(root, &layout).unwrap();
        assert_eq!(
            standalone,
            [
                "third-party/rust/standalone/ws/crates/sdep/2.0.0",
                "third-party/rust/standalone/ws/git/gdep/0.1.0",
            ]
            .map(str::to_owned)
            .into()
        );
        // The root generation's tables: the standalone packages are whole-repository
        // packages, and only the stray BUCK file is a source-tree package among them.
        let mut generated = BTreeSet::new();
        generated.extend(standalone.iter().cloned());
        assert_eq!(
            source_tree_packages(root, &layout, &generated).unwrap(),
            [
                ".",
                "guests/ws",
                "plain",
                "third-party/rust/standalone/ws/crates/stray/0.1.0",
            ]
            .map(str::to_owned)
            .into()
        );
    }

    #[test]
    fn test_standalone_universes_refuse_a_shared_name_and_a_missing_record() {
        use crate::universe::Universe;

        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        for path in [
            "a/ws/Cargo.toml",
            "a/ws/buckal.toml",
            "b/ws/Cargo.toml",
            "b/ws/buckal.toml",
        ] {
            touch(root, path);
        }
        let layout = CellLayout::parse("").unwrap();
        let found = standalone_universes(root, &layout).unwrap();
        // Neither generated: two fixtures sharing a name do not stop generation.
        check_universe_names(&found, None).unwrap();
        assert!(standalone_package_dirs(root, &layout).unwrap().is_empty());
        // Selecting one while the other is unrecorded is allowed...
        let a = Universe::Standalone {
            dir: "a/ws".into(),
            name: "ws".to_owned(),
        };
        check_universe_names(&found, Some(&a)).unwrap();
        // ...but once one has a record, generating the other is refused, whether or
        // not the run writes tables.
        std::fs::write(root.join("a/ws/buckal.snap"), standalone_record(&[])).unwrap();
        let found = standalone_universes(root, &layout).unwrap();
        let b = Universe::Standalone {
            dir: "b/ws".into(),
            name: "ws".to_owned(),
        };
        let error = check_universe_names(&found, Some(&b)).unwrap_err();
        assert!(error.contains("share the directory name `ws`"), "{error}");
        check_universe_names(&found, Some(&a)).unwrap();
        std::fs::write(root.join("b/ws/buckal.snap"), standalone_record(&[])).unwrap();
        let error = standalone_package_dirs(root, &layout).unwrap_err();
        assert!(error.contains("share the directory name `ws`"), "{error}");

        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        for path in [
            "g/ws/Cargo.toml",
            "g/ws/buckal.toml",
            "third-party/rust/standalone/ws/crates/sdep/2.0.0/BUCK",
        ] {
            touch(root, path);
        }
        let error = standalone_package_dirs(root, &layout).unwrap_err();
        assert!(error.contains("has no buckal.snap"), "{error}");
    }

