//! `[package_macro] tables`: a generated Starlark file of the repository's
//! package tables, for a repository macro that needs every package by name (for
//! example a tree staged from every package's exports).
//!
//! - `GENERATED_WHOLE_REPOSITORY_PACKAGES` maps the directory of each BUCK file
//!   generation writes whole (each third-party package's, today
//!   `third-party/rust/crates/<name>/<version>` or
//!   `third-party/rust/git/<name>/<version>`) to its package,
//!   `"<root cell>//<dir>:"`. It is the generator's own inventory
//!   (`super::actions::generated_package_dirs`), not a test of where a path lies,
//!   together with each standalone universe's inventory, read from that
//!   universe's own record (`third-party/rust/standalone/<name>/…`; see
//!   [`standalone_package_dirs`]).
//! - `GENERATED_SOURCE_TREE_PACKAGES` lists every other directory of the root cell
//!   that holds a BUCK file, `"."` for the root, whoever wrote it. It comes from a
//!   walk of the Buck2 project after generation has written its BUCK files, less
//!   the inventory: see [`source_tree_packages`].
//!
//! Both are sorted by their directories' text.

use std::collections::{BTreeMap, BTreeSet};

use cargo_metadata::camino::{Utf8Path, Utf8PathBuf};
use globset::{GlobBuilder, GlobSet, GlobSetBuilder};

use crate::{
    buck::GENERATED_HEADER, buckal_warn, cache::PackageTablesRecord, context::BuckalContext,
};

/// The second line of the tables file, after [`GENERATED_HEADER`], by which
/// generation recognises the file as its own.
pub const PACKAGE_TABLES_MARKER: &str =
    "# Generated by `cargo buckal` from `[package_macro] tables`. Not intended for manual editing.";

/// The name of the dict of third-party packages in the tables file.
pub const WHOLE_REPOSITORY_PACKAGES: &str = "GENERATED_WHOLE_REPOSITORY_PACKAGES";

/// The name of the list of other root-cell packages in the tables file.
pub const SOURCE_TREE_PACKAGES: &str = "GENERATED_SOURCE_TREE_PACKAGES";

/// Directory names that are never a package's: version-control stores, at any
/// depth.
const VCS_DIRECTORIES: [&str; 4] = [".git", ".hg", ".jj", ".sl"];

/// The `[project] ignore` entries `cargo buckal init` writes, which apply at the
/// project root whether or not the repository's `.buckconfig` still lists them.
/// Buck2 ignores `buck-out` anyway.
const BUCKAL_IGNORED_AT_ROOT: [&str; 4] = [".git", ".buckal", "buck-out", "target"];

/// The repository's package tables.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct PackageTables {
    /// Third-party package directory to its package.
    pub whole_repository: BTreeMap<String, String>,
    /// Every other root-cell package directory, `"."` for the root.
    pub source_tree: BTreeSet<String>,
}

/// What the tables need of `.buckconfig`.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct CellLayout {
    /// The name of the root cell (the cell at `.`), `root` if none is named.
    pub root_cell: String,
    /// The project-relative directories of the other cells inside the project.
    pub other_cells: BTreeSet<String>,
    /// The `[project] ignore` patterns.
    pub ignore: Vec<String>,
}

impl CellLayout {
    /// The layout `.buckconfig` text `content` declares: `[cells]` (and the older
    /// `[repositories]`) and `[project] ignore`.
    pub fn parse(content: &str) -> Result<Self, String> {
        let ini = ini::Ini::load_from_str(content)
            .map_err(|error| format!("cannot parse .buckconfig: {error}"))?;
        let mut layout = CellLayout::default();
        for section in ["repositories", "cells"] {
            let Some(cells) = ini.section(Some(section)) else {
                continue;
            };
            for (name, path) in cells.iter() {
                match normalize_cell_path(path) {
                    Some(path) if path.is_empty() => layout.root_cell = name.to_owned(),
                    Some(path) => {
                        layout.other_cells.insert(path);
                    }
                    // Outside the project: nothing of it is walked.
                    None => {}
                }
            }
        }
        if layout.root_cell.is_empty() {
            layout.root_cell = "root".to_owned();
        }
        if let Some(ignore) = ini.section(Some("project")).and_then(|p| p.get("ignore")) {
            layout.ignore = ignore
                .split(|c: char| c == ',' || c.is_whitespace())
                .filter(|pattern| !pattern.is_empty())
                .map(|pattern| pattern.trim_end_matches('/').to_owned())
                .collect();
        }
        Ok(layout)
    }

    /// The layout of the project at `root`, from its `.buckconfig` (an empty one
    /// if there is none).
    pub fn of_project(root: &Utf8Path) -> Result<Self, String> {
        let path = root.join(".buckconfig");
        match std::fs::read_to_string(&path) {
            Ok(content) => Self::parse(&content).map_err(|error| format!("{path}: {error}")),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => Self::parse(""),
            Err(error) => Err(format!("cannot read {path}: {error}")),
        }
    }
}

/// A cell's path as `.buckconfig` writes it, relative to the project root and
/// without `./` or a trailing `/` (`""` for the root), or `None` if it is
/// absolute or leaves the project.
fn normalize_cell_path(path: &str) -> Option<String> {
    let path = path.trim();
    if path.starts_with('/') {
        return None;
    }
    let mut parts: Vec<&str> = Vec::new();
    for part in path.split('/') {
        match part {
            "" | "." => {}
            ".." => {
                parts.pop()?;
            }
            part => parts.push(part),
        }
    }
    Some(parts.join("/"))
}

/// The packages of the BUCK files generation writes whole, `generated` (their
/// directories), in the root cell `root_cell`.
pub fn whole_repository_packages(
    generated: &BTreeSet<String>,
    root_cell: &str,
) -> BTreeMap<String, String> {
    generated
        .iter()
        .map(|dir| (dir.clone(), format!("{root_cell}//{dir}:")))
        .collect()
}

/// Every directory of the root cell of the Buck2 project at `root` that holds a
/// file (or symlink) named `BUCK`, as a project-relative path (`"."` for the
/// root), except the directories of the BUCK files generation writes whole,
/// `generated` (its inventory). Wherever those lie, they are left out by name,
/// and nothing else is.
///
/// The walk is of the file system, after generation has written its BUCK files,
/// so it sees hand-written BUCK files and generated ones alike. It does not
/// follow symlinked directories, and it skips what Buck2 would not see as root-cell
/// packages: the directories of the other cells `layout` declares, paths its
/// `[project] ignore` patterns match, version-control stores (`.git`, `.hg`,
/// `.jj`, `.sl`) at any depth, and `buck-out`, `target` and `.buckal` at the
/// root (the entries `cargo buckal init` writes to `[project] ignore`). An
/// unreadable directory, or a path that is not UTF-8, is an error rather than a
/// gap in the list.
pub fn source_tree_packages(
    root: &Utf8Path,
    layout: &CellLayout,
    generated: &BTreeSet<String>,
) -> Result<BTreeSet<String>, String> {
    Ok(root_cell_files(root, layout)?
        .into_iter()
        .filter_map(|(dir, name)| (name == "BUCK" && !generated.contains(&dir)).then_some(dir))
        .collect())
}

/// Every file (or symlink) of the root cell of the Buck2 project at `root`, as its
/// project-relative directory (`"."` for the root) and its name, walked as
/// [`source_tree_packages`] describes.
fn root_cell_files(root: &Utf8Path, layout: &CellLayout) -> Result<Vec<(String, String)>, String> {
    let ignore = ignore_set(&layout.ignore)?;
    let skipped = |relative: &str, name: &str| -> bool {
        VCS_DIRECTORIES.contains(&name)
            || BUCKAL_IGNORED_AT_ROOT.contains(&relative)
            || layout.other_cells.contains(relative)
            || ignore.is_match(relative)
    };
    let mut files = Vec::new();
    let mut walker = walkdir::WalkDir::new(root)
        .follow_links(false)
        .sort_by_file_name()
        .into_iter();
    while let Some(entry) = walker.next() {
        let entry = entry.map_err(|error| format!("cannot walk {root}: {error}"))?;
        let path = Utf8PathBuf::from_path_buf(entry.path().to_path_buf())
            .map_err(|path| format!("{} is not a UTF-8 path", path.display()))?;
        let relative = path
            .strip_prefix(root)
            .expect("walked below the root")
            .as_str()
            .replace('\\', "/");
        if entry.depth() > 0 && entry.file_type().is_dir() {
            let name = entry.file_name().to_string_lossy();
            if skipped(&relative, &name) {
                walker.skip_current_dir();
            }
            continue;
        }
        if !entry.file_type().is_dir() && !ignore.is_match(&relative) {
            let (dir, name) = relative
                .rsplit_once('/')
                .unwrap_or((".", relative.as_str()));
            files.push((dir.to_owned(), name.to_owned()));
        }
    }
    Ok(files)
}

/// A standalone universe found in the project, and whether it has a generation
/// record (`buckal.snap`) of its own.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FoundUniverse {
    pub universe: crate::universe::Universe,
    pub recorded: bool,
}

/// Every standalone universe of the Buck2 project at `root`, found as
/// [`crate::universe::Universe::of_manifest`] selects one: a directory of the root
/// cell, other than the root, holding both a `Cargo.toml` and a `buckal.toml`,
/// walked as [`source_tree_packages`] describes.
pub fn standalone_universes(
    root: &Utf8Path,
    layout: &CellLayout,
) -> Result<Vec<FoundUniverse>, String> {
    use crate::universe::{CACHE_FILE, CONFIG_FILE, Universe};

    let files = root_cell_files(root, layout)?;
    let present: BTreeSet<(&str, &str)> = files
        .iter()
        .map(|(dir, name)| (dir.as_str(), name.as_str()))
        .collect();
    Ok(files
        .iter()
        .filter(|(dir, name)| {
            dir != "." && name == CONFIG_FILE && present.contains(&(dir.as_str(), "Cargo.toml"))
        })
        .map(|(dir, _)| FoundUniverse {
            universe: Universe::Standalone {
                dir: dir.into(),
                name: dir
                    .rsplit_once('/')
                    .map_or(dir.as_str(), |(_, last)| last)
                    .to_owned(),
            },
            recorded: present.contains(&(dir.as_str(), CACHE_FILE)),
        })
        .collect())
}

/// Refuse two standalone universes that would share a vendor tree
/// (`third-party/rust/standalone/<directory name>`): among those with a record and
/// `selected` (the universe a command is about to generate, if standalone), no two
/// directories may share a name. A universe never generated and not selected
/// writes nothing, so it is not counted: a test fixture's `buckal.toml` does not
/// stop generation.
pub fn check_universe_names(
    found: &[FoundUniverse],
    selected: Option<&crate::universe::Universe>,
) -> Result<(), String> {
    use crate::universe::Universe;

    let mut names: BTreeMap<&str, &Utf8Path> = BTreeMap::new();
    let counted = found
        .iter()
        .filter(|found| found.recorded || Some(&found.universe) == selected)
        .map(|found| &found.universe)
        .chain(selected);
    for universe in counted {
        let Universe::Standalone { dir, name } = universe else {
            continue;
        };
        match names.insert(name, dir) {
            Some(other) if other != dir => {
                return Err(format!(
                    "the standalone workspaces `{other}` and `{dir}` share the directory name `{name}`, so both would vendor into third-party/rust/standalone/{name}; rename one. Nothing is written"
                ));
            }
            _ => {}
        }
    }
    Ok(())
}

/// The directories of the BUCK files every standalone universe of the Buck2
/// project at `root` writes whole (see [`crate::universe`]), so that the root
/// generation classifies them as generated rather than as source-tree packages.
///
/// The universes are [`standalone_universes`]. Each recorded universe's inventory
/// is read from its own generation record, the `buckal.snap` beside its
/// `buckal.toml`: each registry or git package it records, placed under the
/// universe's vendor root as its own generation placed it.
///
/// Refused: universes sharing a vendor tree ([`check_universe_names`]), and a
/// universe whose vendor tree exists but whose record does not (its BUCK files
/// could not be told from hand-written ones). A universe never generated, with
/// neither, contributes nothing.
pub fn standalone_package_dirs(
    root: &Utf8Path,
    layout: &CellLayout,
) -> Result<BTreeSet<String>, String> {
    use crate::universe::CACHE_FILE;

    let found = standalone_universes(root, layout)?;
    check_universe_names(&found, None)?;
    let mut dirs = BTreeSet::new();
    for FoundUniverse { universe, recorded } in &found {
        let dir = universe.config_dir();
        if !recorded {
            let vendor = root.join(universe.vendor_root());
            if vendor.exists() {
                return Err(format!(
                    "{vendor} exists but the standalone workspace `{dir}` has no {CACHE_FILE} recording what generated it; generate it (`cargo buckal migrate --manifest-path {dir}/Cargo.toml`) before the root workspace"
                ));
            }
            continue;
        }
        let record = root.join(dir).join(CACHE_FILE);
        let cache = crate::cache::BuckalCache::load_from(&record)
            .map_err(|error| format!("{record}: {error}"))?;
        for id in cache.package_ids() {
            if let Some(path) = universe
                .vendor_path_relative(id)
                .map_err(|error| format!("{record}: {error:#}"))?
            {
                dirs.insert(path);
            }
        }
    }
    Ok(dirs)
}

/// The `[project] ignore` patterns as Buck2 matches them: globs relative to the
/// project root, in which `*` does not cross a `/`.
fn ignore_set(patterns: &[String]) -> Result<GlobSet, String> {
    let mut set = GlobSetBuilder::new();
    for pattern in patterns {
        let glob = GlobBuilder::new(pattern)
            .literal_separator(true)
            .build()
            .map_err(|error| format!("[project] ignore pattern {pattern:?}: {error}"))?;
        set.add(glob);
    }
    set.build()
        .map_err(|error| format!("[project] ignore: {error}"))
}

/// A Starlark string literal of `text`.
fn starlark_string(text: &str) -> String {
    let mut literal = String::with_capacity(text.len() + 2);
    literal.push('"');
    for c in text.chars() {
        match c {
            '\\' => literal.push_str("\\\\"),
            '"' => literal.push_str("\\\""),
            '\n' => literal.push_str("\\n"),
            '\r' => literal.push_str("\\r"),
            '\t' => literal.push_str("\\t"),
            c => literal.push(c),
        }
    }
    literal.push('"');
    literal
}

impl PackageTables {
    /// The tables file's text.
    pub fn render(&self) -> String {
        let mut text = format!(
            "{GENERATED_HEADER}\n{PACKAGE_TABLES_MARKER}\n#\n\
             # {WHOLE_REPOSITORY_PACKAGES}: the directory of each third-party package\n\
             # generation writes a BUCK file for, mapped to its package.\n\
             # {SOURCE_TREE_PACKAGES}: every other directory of the root cell that\n\
             # holds a BUCK file, \".\" for the root.\n\n"
        );
        if self.whole_repository.is_empty() {
            text.push_str(&format!("{WHOLE_REPOSITORY_PACKAGES} = {{}}\n"));
        } else {
            text.push_str(&format!("{WHOLE_REPOSITORY_PACKAGES} = {{\n"));
            for (dir, package) in &self.whole_repository {
                text.push_str(&format!(
                    "    {}: {},\n",
                    starlark_string(dir),
                    starlark_string(package)
                ));
            }
            text.push_str("}\n");
        }
        text.push('\n');
        if self.source_tree.is_empty() {
            text.push_str(&format!("{SOURCE_TREE_PACKAGES} = []\n"));
        } else {
            text.push_str(&format!("{SOURCE_TREE_PACKAGES} = [\n"));
            for dir in &self.source_tree {
                text.push_str(&format!("    {},\n", starlark_string(dir)));
            }
            text.push_str("]\n");
        }
        text
    }
}

/// Whether `content` is a tables file generation wrote: its first two lines are
/// [`GENERATED_HEADER`] and [`PACKAGE_TABLES_MARKER`].
pub fn is_generated_tables(content: &str) -> bool {
    let mut lines = content.lines();
    lines.next().map(str::trim_end) == Some(GENERATED_HEADER)
        && lines.next().map(str::trim_end) == Some(PACKAGE_TABLES_MARKER)
}

/// The record `buckal.snap` keeps of the tables file a generation wrote: its
/// path and a BLAKE3 digest of its content, so that a change of the tables
/// changes the record, and so that a later generation knows which file to
/// remove once `tables` is unset or moved.
pub fn digest(content: &str) -> String {
    hex::encode(blake3::hash(content.as_bytes()).as_bytes())
}

/// What a generation does about the tables file, decided before it writes
/// anything (so that a refusal leaves every file as it was) and carried out after
/// it has written its BUCK files (so that the walk sees them).
#[derive(Debug)]
pub struct TablesPlan {
    root: Utf8PathBuf,
    /// The configured tables file, project-relative.
    write: Option<String>,
    /// The file an earlier generation wrote that `tables` no longer names.
    stale: Option<String>,
    /// Every standalone universe's generated package directories, read before
    /// anything is written so that a refusal leaves every file as it was.
    standalone: BTreeSet<String>,
}

impl TablesPlan {
    /// The plan for `ctx`, with `previous` the tables file the previous
    /// generation recorded. `Ok(None)`: nothing to do. An `Err` is a refusal: the
    /// configured path holds a file generation did not write, or the Buck2
    /// project root is unknown.
    pub fn new(
        ctx: &BuckalContext,
        previous: Option<&PackageTablesRecord>,
    ) -> Result<Option<Self>, String> {
        let write = ctx.repo_config.package_macro.tables.clone();
        if write.is_some() && *crate::universe::selected() != crate::universe::Universe::Root {
            return Err(format!(
                "`[package_macro] tables` is set in the configuration of the standalone workspace `{}`; the tables are the whole project's, so only the Buck2 project's own `buckal.toml` may set them. Nothing is written",
                crate::universe::selected().config_dir()
            ));
        }
        let stale = previous
            .map(|record| record.path.clone())
            .filter(|path| Some(path) != write.as_ref());
        if write.is_none() && stale.is_none() {
            return Ok(None);
        }
        let root = ctx.buck2_root.clone().ok_or_else(|| {
            "[package_macro] tables: the Buck2 project root is unknown, so the tables file cannot be placed"
                .to_owned()
        })?;
        if let Some(path) = &write {
            let full = root.join(path);
            match std::fs::read_to_string(&full) {
                Ok(content) if !is_generated_tables(&content) => {
                    return Err(format!(
                        "{full}: `[package_macro] tables` names this file, but generation did not write it (its first lines are not `{GENERATED_HEADER}` and `{PACKAGE_TABLES_MARKER}`); move it away or name another path. Nothing is written"
                    ));
                }
                Ok(_) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => {
                    return Err(format!(
                        "{full}: `[package_macro] tables` names this path, which cannot be read: {error}. Nothing is written"
                    ));
                }
            }
        }
        // `tables` is refused to a standalone universe above, so this is the root
        // generation, whose tables hold every standalone universe's packages too.
        let standalone = if write.is_some() {
            standalone_package_dirs(&root, &CellLayout::of_project(&root)?)
                .map_err(|error| format!("{error}. Nothing is written"))?
        } else {
            BTreeSet::new()
        };
        Ok(Some(Self {
            root,
            write,
            stale,
            standalone,
        }))
    }

    /// Remove the stale file, if generation wrote it, with a warning; then write
    /// the tables file, if configured, from `generated`, the generator's
    /// inventory of the BUCK files it writes whole, and return its record for
    /// `buckal.snap`.
    pub fn execute(
        self,
        generated: &BTreeSet<String>,
    ) -> Result<Option<PackageTablesRecord>, String> {
        if let Some(path) = &self.stale {
            let full = self.root.join(path);
            match std::fs::read_to_string(&full) {
                Ok(content) if is_generated_tables(&content) => {
                    std::fs::remove_file(&full)
                        .map_err(|error| format!("cannot remove {full}: {error}"))?;
                    buckal_warn!(format!(
                        "{full}: removing the package tables an earlier generation wrote from `[package_macro] tables`, which no longer names this file"
                    ));
                }
                Ok(_) => buckal_warn!(format!(
                    "{full}: an earlier generation wrote its package tables here, but the file is no longer the one it wrote; it is left in place"
                )),
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => return Err(format!("cannot read {full}: {error}")),
            }
        }
        let Some(path) = self.write else {
            return Ok(None);
        };
        let layout = CellLayout::of_project(&self.root)?;
        // The root generation's inventory and every standalone universe's.
        let mut generated = generated.clone();
        generated.extend(self.standalone.iter().cloned());
        let generated = &generated;
        let tables = PackageTables {
            whole_repository: whole_repository_packages(generated, &layout.root_cell),
            source_tree: source_tree_packages(&self.root, &layout, generated)?,
        };
        let text = tables.render();
        let full = self.root.join(&path);
        if std::fs::read_to_string(&full).ok().as_deref() != Some(text.as_str()) {
            if let Some(dir) = full.parent() {
                std::fs::create_dir_all(dir)
                    .map_err(|error| format!("cannot create {dir}: {error}"))?;
            }
            std::fs::write(&full, &text)
                .map_err(|error| format!("cannot write {full}: {error}"))?;
        }
        Ok(Some(PackageTablesRecord {
            path,
            blake3: digest(&text),
        }))
    }
}

